    ON FUTURE TABLES IN SCHEMA EG_ENV_SALES_ANALYTICS_DB.PRE_REPORT
    TO ROLE EG_ENV_SALES_ANALYTICS_ENGR_FR;

GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE, REFERENCES
    ON ALL TABLES IN SCHEMA EG_ENV_SALES_ANALYTICS_DB.REPORT
    TO ROLE EG_ENV_SALES_ANALYTICS_ENGR_FR;

