    TO ROLE EG_ENV_SALES_ANALYTICS_ENGR_FR;

-- Warehouse usage
GRANT USAGE ON WAREHOUSE EG_ENV_SALES_ANALYTICS_ENGR_WH 
    TO ROLE EG_ENV_SALES_ANALYTICS_ENGR_FR;


-- Grant read role for ANALYTICS DB
-- Visibility
GRANT USAGE ON DATABASE EG_ENV_SALES_ANALYTICS_DB 
    TO ROLE EG_ENV_SALES_ANALYTICS_READER_FR;
GRANT USAGE ON ALL SCHEMAS IN DATABASE EG_ENV_SALES_ANALYTICS_DB 
    TO ROLE EG_ENV_SALES_ANALYTICS_READER_FR;
GRANT USAGE ON FUTURE SCHEMAS IN DATABASE EG_ENV_SALES_ANALYTICS_DB 
